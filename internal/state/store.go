var ErrDenied = errors.New("grant inactive")
var ErrConflict = errors.New("idempotency conflict or request pending")

type Store interface {
	Create(context.Context, security.Grant) error
	Get(context.Context, string) (security.Grant, error)
	Revoke(context.Context, string) error
	Reserve(context.Context, string, string) ([]byte, bool, error)
	Complete(context.Context, string, string, []byte) error
}

// Recheck all ancestors on EVERY request, including retries; no positive cache.
func Active(ctx context.Context, s Store, id string, now time.Time) (security.Grant, error) {
	g, err := s.Get(ctx, id)
	if err != nil {
		return g, err
	}
	leaf := g
	for i := 0; i <= security.MaxDepth; i++ {
		if g.Revoked || g.Expires <= now.Unix() {
			return leaf, ErrDenied
		}
		if g.Parent == "" {
			if g.Depth != 0 {
				return leaf, ErrDenied
			}
			return leaf, nil
		}
		parent, e := s.Get(ctx, g.Parent)
		if e != nil {
			return leaf, e
		}
		if !security.Attenuates(parent, g) {
			return leaf, ErrDenied
		}
		g = parent
	}
	return leaf, ErrDenied
}

type receipt struct {
	Digest string `json:"digest"`
	Done   bool   `json:"done"`
	Result []byte `json:"result,omitempty"`
}
type Memory struct {
	mu       sync.Mutex
	grants   map[string]security.Grant
	receipts map[string]receipt
}

func NewMemory() *Memory {
	return &Memory{grants: map[string]security.Grant{}, receipts: map[string]receipt{}}
}
func (m *Memory) Create(_ context.Context, g security.Grant) error {
	m.mu.Lock()
	defer m.mu.Unlock()
	if _, ok := m.grants[g.ID]; ok {
		return ErrConflict
	}
	m.grants[g.ID] = g
	return nil
}
func (m *Memory) Get(_ context.Context, id string) (security.Grant, error) {
	m.mu.Lock()
	defer m.mu.Unlock()
	g, ok := m.grants[id]
	if !ok {
		return g, ErrDenied
	}
	return g, nil
}
func (m *Memory) Revoke(_ context.Context, id string) error {
	m.mu.Lock()
	defer m.mu.Unlock()
	g, ok := m.grants[id]
	if !ok {
		return ErrDenied
	}
	g.Revoked = true
	m.grants[id] = g
	return nil
}
func (m *Memory) Reserve(_ context.Context, k, d string) ([]byte, bool, error) {
	m.mu.Lock()
	defer m.mu.Unlock()
	r, ok := m.receipts[k]
	if ok {
		if r.Digest != d || !r.Done {
			return nil, false, ErrConflict
		}
		return r.Result, false, nil
	}
	m.receipts[k] = receipt{Digest: d}
	return nil, true, nil
}
func (m *Memory) Complete(_ context.Context, k, d string, b []byte) error {
	m.mu.Lock()
	defer m.mu.Unlock()
	r, ok := m.receipts[k]
	if !ok || r.Digest != d || r.Done {
		return ErrConflict
	}
	m.receipts[k] = receipt{Digest: d, Done: true, Result: b}
	return nil
}

type Redis struct{ Client *redis.Client }

func (s *Redis) Create(ctx context.Context, g security.Grant) error {
	b, e := json.Marshal(g)
	if e != nil {
		return e
	}
	ok, e := s.Client.SetNX(ctx, "grant:"+g.ID, b, 10*time.Minute).Result()
	if e == nil && !ok {
		return ErrConflict
	}
	return e
}
func (s *Redis) Get(ctx context.Context, id string) (security.Grant, error) {
	var g security.Grant
	b, e := s.Client.Get(ctx, "grant:"+id).Bytes()
	if e != nil {
		return g, e
	}
	e = json.Unmarshal(b, &g)
	return g, e
}

var revokeScript = redis.NewScript(`local b=redis.call('GET',KEYS[1]); if not b then return 0 end; local g=cjson.decode(b); g.revoked=true; redis.call('SET',KEYS[1],cjson.encode(g),'KEEPTTL'); return 1`)

func (s *Redis) Revoke(ctx context.Context, id string) error {
	n, e := revokeScript.Run(ctx, s.Client, []string{"grant:" + id}).Int()
	if e == nil && n != 1 {
		return ErrDenied
	}
	return e
}

// Pending receipts are deliberately retained: an uncertain write is never replayed.
// Durability requires Redis AOF plus external reconciliation after infrastructure loss.
var reserveScript = redis.NewScript(`local b=redis.call('GET',KEYS[1]); if b then local r=cjson.decode(b); if r.digest~=ARGV[1] or not r.done then return {'conflict',''} end; return {'cached',r.result} end; redis.call('SET',KEYS[1],ARGV[2]); return {'new',''}`)

func (s *Redis) Reserve(ctx context.Context, k, d string) ([]byte, bool, error) {
	b, _ := json.Marshal(receipt{Digest: d})
	v, e := reserveScript.Run(ctx, s.Client, []string{"receipt:" + k}, d, string(b)).StringSlice()
	if e != nil {
		return nil, false, e
	}
	if len(v) != 2 {
		return nil, false, errors.New("invalid receipt response")
	}
	switch v[0] {
	case "new":
		return nil, true, nil
	case "cached":
		result, e := jsonDecodeBytes(v[1])
		return result, false, e
	default:
		return nil, false, ErrConflict
	}
}
func jsonDecodeBytes(s string) ([]byte, error) {
	var b []byte // Lua returns the base64 representation generated by encoding/json.
	encoded, _ := json.Marshal(s)
	e := json.Unmarshal(encoded, &b)
	return b, e
}

var completeScript = redis.NewScript(`local b=redis.call('GET',KEYS[1]); if not b then return 0 end; local r=cjson.decode(b); if r.digest~=ARGV[1] or r.done then return 0 end; redis.call('SET',KEYS[1],ARGV[2]); return 1`)

func (s *Redis) Complete(ctx context.Context, k, d string, result []byte) error {
	b, _ := json.Marshal(receipt{Digest: d, Done: true, Result: result})
	n, e := completeScript.Run(ctx, s.Client, []string{"receipt:" + k}, d, string(b)).Int()
	if e == nil && n != 1 {
		return fmt.Errorf("complete: %w", ErrConflict)
	}
	return e
}
